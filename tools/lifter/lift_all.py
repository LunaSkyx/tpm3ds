"""Lift every guest module the game runs, from the player's own GAMEDATA/BIN.

  python -I tools/lifter/lift_all.py <GAMEDATA dir> <out dir>

WMAIN.EXE loads at its preferred base. The game's own DLLs (Bink video,
iMUSE music) are recompiled too instead of re-implemented; both prefer
0x10000000, which is outside the guest arena, so they are rebased into the
gap between the exe image and the guest heap. The runtime loader reads the
module list (base, dispatch table) from the generated lifted_modules.c, so
the lifter and loader can never disagree on a base.
"""
import os
import subprocess
import sys

MODULES = [  # (file in BIN/, import name, C prefix, load base or None for preferred)
    ('WMAIN.EXE', 'WMAIN.EXE', 'wmain', None),
    ('BINKW32.DLL', 'binkw32.dll', 'bink', 0x008e0000),
    ('IMUSE.DLL', 'iMUSE.DLL', 'imuse', 0x00920000),
]


def main():
    data, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    here = os.path.dirname(os.path.abspath(__file__))
    for fname, _, prefix, base in MODULES:
        path = os.path.join(data, 'BIN', fname)
        if not os.path.exists(path):
            raise SystemExit('lift_all: %s not found (needs the player\'s own game files)' % path)
        cmd = [sys.executable, '-I', os.path.join(here, 'lift.py'), path, out, '--prefix', prefix]
        if base is not None:
            cmd += ['--base', '0x%08x' % base]
        print('lift_all: %s -> %s_*' % (fname, prefix), flush=True)
        subprocess.check_call(cmd)
    with open(os.path.join(out, 'lifted_modules.c'), 'w') as fo:
        fo.write('/* GENERATED by tools/lifter/lift_all.py - module list for core/guest.c. */\n')
        fo.write('#include "core/guest.h"\n')
        for _, _, prefix, _ in MODULES:
            fo.write('extern const guest_fn_entry %s_fn_tab[];\nextern const uint32_t %s_fn_count;\n' % (prefix, prefix))
        fo.write('const guest_module g_lifted_modules[] = {\n')
        for fname, imp, prefix, base in MODULES:
            fo.write('    {"%s", "%s", 0x%08xu, %s_fn_tab, &%s_fn_count},\n'
                     % (fname, imp, base or 0, prefix, prefix))
        fo.write('};\nconst uint32_t g_lifted_module_count = %d;\n' % len(MODULES))


if __name__ == '__main__':
    main()
