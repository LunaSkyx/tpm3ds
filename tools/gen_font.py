"""Generates source/pal/3ds/ui_font.h: anti-aliased ASCII bitmap fonts for the bottom-screen UI.
The font is Pillow's built-in default (Aileron, CC0 / public domain), so the generated header carries no licence
obligations. Run: python tools/gen_font.py"""
import sys
from PIL import ImageFont

SIZES = [("S", 10), ("M", 13), ("L", 18)]
out = ["/* GENERATED by tools/gen_font.py (Aileron, CC0). Do not edit. */",
       "#pragma once", "#include <stdint.h>",
       "typedef struct { uint8_t adv, w, h; int8_t xo, yo; uint16_t off; } ui_glyph;",
       "typedef struct { uint8_t height, ascent; const ui_glyph *g; const uint8_t *a; } ui_font_t;"]
for tag, px in SIZES:
    f = ImageFont.load_default(size=px)
    asc, desc = f.getmetrics()
    glyphs, data = [], []
    for c in range(32, 127):
        ch = chr(c)
        adv = int(round(f.getlength(ch)))
        if ch == " ":
            glyphs.append((adv, 0, 0, 0, 0, len(data)))
            continue
        mask = f.getmask(ch, mode="L")
        w, h = mask.size
        bx0, by0, bx1, by1 = f.getbbox(ch)
        off = len(data)
        data.extend(bytes(mask)[: w * h])
        glyphs.append((adv, w, h, bx0, by0, off))
    out.append("static const ui_glyph ui_g_%s[95] = {" % tag)
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append("static const uint8_t ui_a_%s[%d] = {" % (tag, max(1, len(data))))
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append("static const ui_font_t ui_font_%s = { %d, %d, ui_g_%s, ui_a_%s };" % (tag, asc + desc, asc, tag, tag))
open("source/pal/3ds/ui_font.h", "w", newline="\n").write("\n".join(out) + "\n")
print("ok")
